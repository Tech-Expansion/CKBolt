import type { ccc } from "@ckb-ccc/core";
import { toHexQuantity } from "../../../src/common/utils/amount.util";
import type { Script } from "../../../src/domain/types";
import type { CkbChain } from "./ckb";
import { FNN_DEP_TYPE_CODE, FNN_UDT_WHITELIST_ENV, RUSD_UDT_NAME } from "./devnet.constants";
import { toFnnScript, type FnnNodeInfo } from "./fiber";

/**
 * The devnet's RUSD stand-in: an xUDT (no extension) owned by the genesis issuer key. Its type script is fully
 * determined by the chain, so the bootstrap and the smoke test derive it instead of storing it.
 */
export interface RusdStandIn {
  issuer: ccc.Signer;
  typeScript: Script;
}

export async function rusdStandIn(ckb: CkbChain, issuerPrivateKey: string): Promise<RusdStandIn> {
  const issuer = ckb.signer(issuerPrivateKey);
  return { issuer, typeScript: ckb.xudtTypeOwnedBy(await ckb.lockOf(issuer)) };
}

/** True when the node's UDT whitelist has the RUSD stand-in under its name. */
export function nodeWhitelistsRusd(info: FnnNodeInfo, rusd: Script): boolean {
  return info.udt_cfg_infos.some(
    ({ name, script }) =>
      name === RUSD_UDT_NAME &&
      script.code_hash === rusd.codeHash &&
      script.hash_type === rusd.hashType &&
      script.args.toLowerCase() === rusd.args.toLowerCase(),
  );
}

/**
 * devnet/state/fnn-udt.env: the fnn UDT whitelist (a JSON list of UdtArgInfo) holding only the RUSD stand-in. `args`
 * is a regex in fnn; the exact args match only this token. Single quotes keep compose from interpreting the JSON.
 */
export function renderUdtWhitelistEnv(rusd: Script, xudtCellDep: CkbChain["xudt"]["outPoint"], autoAcceptAmount: bigint): string {
  if (autoAcceptAmount > BigInt(Number.MAX_SAFE_INTEGER)) {
    throw new Error("DEVNET_RUSD_AUTO_ACCEPT is too large for fnn's JSON whitelist (max 2^53 - 1)");
  }
  const whitelist = [
    {
      name: RUSD_UDT_NAME,
      script: toFnnScript(rusd),
      auto_accept_amount: Number(autoAcceptAmount),
      cell_deps: [
        { cell_dep: { out_point: { tx_hash: xudtCellDep.txHash, index: toHexQuantity(xudtCellDep.index) }, dep_type: FNN_DEP_TYPE_CODE } },
      ],
    },
  ];
  return [
    "# Generated by devnet/scripts/bootstrap.ts: the RUSD stand-in (xUDT) in the fnn UDT whitelist.",
    `${FNN_UDT_WHITELIST_ENV}='${JSON.stringify(whitelist)}'`,
    "",
  ].join("\n");
}
